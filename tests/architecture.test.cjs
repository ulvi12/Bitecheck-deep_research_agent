const {readFileSync}=require('node:fs');
const vm=require('node:vm');
const assert=require('node:assert/strict');
const html=readFileSync(require('node:path').join(__dirname,'..','index.html'),'utf8');
const code=html.slice(html.indexOf('// Architecture view'),html.indexOf('let currentArchitecture='));
const context=vm.createContext({});vm.runInContext(code,context);
let events=[],sequence=0;
const add=(node,kind,id,extra={})=>events.push({sequence:++sequence,node,kind,operation_id:id,agent:node==='lead_plan'||node==='lead_check'?'Lead':node,...extra});
const view=(status='running',extra={})=>context.architectureState({events,...extra},status);
assert.ok(Object.values(view('idle').nodes).every(n=>n.status==='waiting'));
add('clarifier','model_started','c');assert.equal(view().nodes.clarifier.status,'active');
add('clarifier','model_finished','c');
add('lead_plan','model_started','l1');assert.equal(view().edges.clarify_plan.status,'active');
add('lead_plan','model_finished','l1');
for(const specialty of ['product','regulation','evidence'])add('lead_plan','tool_started','task-'+specialty,{tool:'research',specialty});
add('product','model_started','p');add('regulation','model_started','r');
let state=view('running',{queued_agents:['Evidence Researcher 3']});
assert.equal(state.nodes.product.status,'active');assert.equal(state.nodes.regulation.status,'active');
assert.equal(state.nodes.evidence.status,'queued');assert.equal(state.nodes.lead_plan.status,'done');
assert.equal(state.edges.plan_product.status,'active');
add('product','model_finished','p');add('product','tool_started','page',{tool:'read_source'});
assert.equal(view().nodes.product.status,'active');
add('product','tool_finished','page',{tool:'read_source'});
add('regulation','model_finished','r');add('evidence','model_started','e');add('evidence','model_finished','e');
for(const specialty of ['product','regulation','evidence'])add('lead_plan','tool_finished','task-'+specialty,{tool:'research',specialty});
add('lead_check','model_started','l2');
assert.equal(view().nodes.lead_check.status,'active');assert.equal(view().edges.product_check.status,'done');
add('lead_check','model_finished','l2');
add('lead_plan','tool_started','follow-up',{tool:'research',specialty:'product'});
assert.equal(view().edges.check_plan.status,'done');assert.equal(view().edges.plan_product.status,'active');
add('lead_plan','tool_finished','follow-up',{tool:'research',specialty:'product'});
add('writer','model_started','w1');assert.equal(view().edges.check_writer.status,'active');
add('writer','model_finished','w1');add('reviewer','model_started','a1');
assert.equal(view().edges.writer_review.status,'active');
add('reviewer','model_finished','a1');add('reviewer','tool_failed','audit1',{tool:'check_report',decision:'revise'});
add('writer','model_started','w2');
assert.equal(view().nodes.writer.status,'active');assert.equal(view().edges.review_writer.status,'active');
assert.equal(view().nodes.answer.status,'waiting');
let stopped=view('timeout');assert.equal(stopped.nodes.writer.status,'interrupted');assert.equal(stopped.nodes.answer.status,'waiting');
assert.ok(Object.values(stopped.edges).every(e=>e.status!=='active'));
add('writer','model_finished','w2');add('reviewer','model_started','a2');add('reviewer','model_finished','a2');
add('reviewer','tool_finished','audit2',{tool:'check_report',decision:'approved'});
state=view('complete');assert.equal(state.nodes.answer.status,'done');assert.equal(state.edges.review_answer.status,'done');
assert.ok(Object.values(state.nodes).every(n=>n.status!=='active'));
assert.equal(context.architectureState({events:[]},'clarification').nodes.clarifier.status,'needs_input');
assert.equal(context.architectureState({events:[]},'complete').nodes.answer.status,'waiting');
assert.ok(html.indexOf('class="suggestions"')<html.indexOf('id="conversation"'));
console.log('Passed: parallel activity, queueing, tool reads, handoffs, follow-up loop, revision loop, timeout, clarification, saved-answer isolation');
