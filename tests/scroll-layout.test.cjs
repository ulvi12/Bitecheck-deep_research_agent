const assert=require('node:assert/strict');
const {readFileSync}=require('node:fs');
const vm=require('node:vm');
const html=readFileSync(require('node:path').join(__dirname,'..','index.html'),'utf8');
const script=html.split('<script>')[1].split('</script>')[0];
const calls=[];
const chat={scrollTop:120,getBoundingClientRect:()=>({top:80}),scrollTo:options=>calls.push(options)};
const toggle={textContent:'',attributes:{},setAttribute(k,v){this.attributes[k]=v}};
const body={dataset:{}};
const context=vm.createContext({$:id=>({'chat-scroll':chat,'toggle-map':toggle}[id]),document:{body},window:{scrollTo:()=>{throw Error('The page must not scroll')}}});
vm.runInContext(script.slice(script.indexOf('function scrollTo('),script.indexOf('function save(')),context);
context.scrollTo({getBoundingClientRect:()=>({top:650})});
assert.equal(calls.length,1);assert.equal(calls[0].top,670);
chat.scrollTop=0;context.scrollTo({getBoundingClientRect:()=>({top:0})});
assert.equal(calls[1].top,0);
context.setMapOpen(true);assert.equal(body.dataset.mapOpen,'true');
assert.equal(toggle.textContent,'Back to chat');assert.equal(toggle.attributes['aria-expanded'],'true');
context.setMapOpen(false);assert.equal(toggle.textContent,'Agent map');assert.equal(toggle.attributes['aria-expanded'],'false');
assert.ok(!script.includes('scrollIntoView('));assert.ok(!script.includes('window.scrollTo('));
const responseStart=script.indexOf('const data=await r.json();stopProgress()');
assert.ok(responseStart>=0);
const responseBlock=script.slice(responseStart,script.indexOf('}catch{',responseStart));
assert.ok(!responseBlock.includes('scrollTo('),'Finishing an answer must preserve the user’s reading position');
const css=html.split('<style>')[1].split('</style>')[0];
assert.match(css,/html\{[^}]*overflow:hidden/);
assert.match(css,/#chat-scroll\{[^}]*overflow-y:auto/);
assert.match(css,/#agent-map\{[^}]*grid-template-rows:auto minmax\(0,1fr\)/);
assert.match(css,/\.map-content\{[^}]*overflow:hidden/);
assert.match(css,/\.architecture-svg\{[^}]*height:100%[^}]*min-height:0/);
assert.ok(!css.includes('position:fixed'));assert.ok(!css.includes('position:sticky'));
assert.ok(html.indexOf('class="chat-pane"')<html.indexOf('id="chat-scroll"'));
assert.ok(html.indexOf('</main>')<html.indexOf('id="composer"'));
assert.ok(html.indexOf('id="composer"')<html.indexOf('class="architecture-panel"'));
console.log('Passed: chat-relative scrolling, completion position preservation, narrow-screen navigation, viewport and pane layout contracts');
